import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {Script,createContext} from 'node:vm';
import {PLANNING_DEPARTMENTS,departmentForPlanningRole,planningVerdictSummary,planningRejectReason} from '../lib/planeaciones_dictamen.js';
const assertVote=(decisions,expected)=>{
  const votes=decisions.map((decision,i)=>({departamento:PLANNING_DEPARTMENTS[i],dictamen:decision}));
  const result=planningVerdictSummary(votes);
  assert.equal(result.estado,expected);
  return result;
};
assert.equal(departmentForPlanningRole('control'),'control_escolar');
assert.equal(departmentForPlanningRole('archivo_escolar'),null);
assert.equal(departmentForPlanningRole('docente'),null);
assert.equal(assertVote(['aprobada','aprobada','aprobada'],'aprobada').valida,true);
assert.equal(assertVote(['aprobada','aprobada','aprobada','rechazada'],'aprobada').valida,true);
assert.equal(assertVote(['aprobada','aprobada','rechazada','rechazada'],'apelacion_requerida').requiereApelacion,true);
assert.equal(assertVote(['rechazada','rechazada'],'apelacion_requerida').requiereApelacion,true);
assert.equal(assertVote(['aprobada','aprobada'],'en_revision').valida,false);
assert.throws(()=>planningRejectReason('No se acepta.'),/30/);
assert.match(planningRejectReason('Faltan objetivos de aprendizaje y criterios de evaluación verificables.'),/objetivos/);
const root=new URL('../',import.meta.url);
const api=await readFile(new URL('api/data.js',root),'utf8');
const html=await readFile(new URL('index.html',root),'utf8');
const snippet=api.match(/function normalizeEvaluationItems\(items\)\{[\s\S]*?\n\}/)?.[0];
assert.ok(snippet,'Normalizer exists');
const ctx=createContext({Number,Object,Array,Error,String});
new Script(snippet).runInContext(ctx);
const parts=ctx.normalizeEvaluationItems([{nombre:'Tareas',ponderacion:30},{nombre:'Proyecto',ponderacion:40},{nombre:'Examen',ponderacion:30}]);
assert.deepEqual(Array.from(parts,x=>x.maximo),[3,4,3]);
assert.throws(()=>ctx.normalizeEvaluationItems([{nombre:'Proyecto',ponderacion:-5}]),/ponderación/);
assert.match(api,/jaguar_firmar_dictamen_planeacion/);
assert.match(api,/getPlanningSignaturePreview/);
assert.match(api,/appealTeacherPlanning/);
assert.match(api,/Una actividad que intentas quitar ya tiene calificaciones/);
assert.doesNotMatch(api,/await adminClient\.from\('evaluacion_notas'\)\.delete\(\)\.eq\('rubrica_id',rubric\.id\);/);
assert.match(html,/formato_version'\)\)!==4/);
assert.match(html,/jaguarPlanningAppealSubmit/);
assert.match(html,/Registrar calificaciones con rúbrica/);
assert.match(html,/\['JAGUAR_META','ITHLA_META'\]/);
console.log('PASS V5.4: 4 roles, voting threshold, appeals, argument requirement, weight conversion, Excel V4, no destructive rubric edit');
